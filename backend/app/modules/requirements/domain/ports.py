"""Ports implemented by infrastructure adapters."""
from typing import Protocol

from .entities import RequirementEntity


class RequirementRepositoryPort(Protocol):
    def create(self, *, title: str, description: str) -> RequirementEntity: ...
    def get(self, requirement_id: object) -> RequirementEntity | None: ...
    def update(
        self, requirement_id: object, *, title: str | None, description: str | None
    ) -> RequirementEntity | None: ...
    def transition(self, requirement_id: object, *, target_status: str, allowed_from: frozenset[str]) -> RequirementEntity | None: ...
    def history(self, requirement_id: object) -> list[object] | None: ...
    def set_archived(self, requirement_id: object, *, archived: bool) -> RequirementEntity | None: ...
    def list_page(self, *, limit: int, offset: int, query: str | None = None) -> tuple[list[RequirementEntity], int]: ...
